def run():
    print("Deleting old records (except superusers)...")
    CustomUser.objects.filter(is_superuser=False).delete()
    Post.objects.all().delete()
    Tag.objects.all().delete()

    print("Generating tags...")
    tag_objs = []
    for tag_name in TAGS:
        t, _ = Tag.objects.get_or_create(name=tag_name)
        tag_objs.append(t)

    print("Generating users with realistic usernames...")
    users = []
    for en_name, fa_first, fa_last in USER_PROFILES:
        # Generate varied username formats
        formats = [
            en_name, 
            f"{en_name}_{random.randint(70, 99)}", 
            f"{en_name}.dev", 
            f"{en_name}{random.randint(10, 99)}"
        ]
        username = random.choice(formats)
        
        # Ensure uniqueness
        while CustomUser.objects.filter(username=username).exists():
             username = f"{en_name}_{random.randint(1000,9999)}"
             
        user = CustomUser.objects.create_user(
            username=username,
            password='password123',
            first_name=fa_first,
            last_name=fa_last,
            phone_number=f"0912{random.randint(1000000, 9999999)}",
            bio=f"سلام! من {fa_first} {fa_last} هستم. توسعه‌دهنده و علاقه‌مند به یادگیری تکنولوژی‌های جدید."
        )
        users.append(user)
    
    print("Generating posts...")
    posts = []
    for _ in range(40):
        author = random.choice(users)
        content = random.choice(POST_CONTENTS)
        post = Post.objects.create(author=author, content=content)
        
        # Assign 1 to 4 random tags
        post.tags.set(random.sample(tag_objs, k=random.randint(1, 4)))
        posts.append(post)
        
    print("Generating likes and comments...")
    for post in posts:
        # Generate random likes
        likers = random.sample(users, k=random.randint(4, 18))
        for liker in likers:
            Like.objects.create(user=liker, post=post)
            
        # Generate random comments
        for _ in range(random.randint(2, 6)):
            commenter = random.choice(users)
            content = random.choice(COMMENT_CONTENTS)
            Comment.objects.create(post=post, author=commenter, content=content)

    print("========================================")
    print("Data generation completed successfully! 🎉")
    print(f"Total tags created: {len(tag_objs)}")
    print(f"Total users created: {len(users)}")
    print(f"Total posts created: {len(posts)}")
    print("Default password for all new users: password123")
    print("========================================")

if __name__ == '__main__':
    run()
